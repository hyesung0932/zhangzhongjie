#!/bin/bash
# 掌中界 · 生成「发同事测试」包（安装器 + 给同事的说明 + 反馈模板，打成一个 zip）
#
# 用法：
#   bash installer/make-test-package.sh <版本> [输出目录]
# 默认输出到 D:\掌中界\发同事测试\
set -e
VER="$1"; DEST="${2:-/d/掌中界/发同事测试}"
[ -n "$VER" ] || { echo "用法: make-test-package.sh <版本> [输出目录]"; exit 1; }

SETUP="/d/掌中界/安装包/ZhangZhongJie-Setup-$VER-x64.exe"
[ -f "$SETUP" ] || { echo "缺安装器：$SETUP（先跑 pack.sh）"; exit 1; }

STAGE="$DEST/_staging-$VER"
rm -rf "$STAGE"; mkdir -p "$STAGE/1-安装包"
cp "$SETUP" "$STAGE/1-安装包/"
# 使用手册也一起给同事：安装目录里本来就带，但先给一份电子版，没装之前也能看
cp "$(dirname "$0")/使用手册.html" "$STAGE/1-安装包/使用手册.html"

cat > "$STAGE/说明-先看这个.txt" <<EOF
掌中界 $VER · 测试说明
=================================

这个是什么
  一个 Windows 桌面画布工具：把「网页 / 文件夹 / 便签」当成一张张草纸摆在画布上，
  可以随手拖动、推开、对齐，也可以把一整张画布存成模板。

怎么装（不需要管理员权限）
  1. 双击  1-安装包\\ZhangZhongJie-Setup-$VER-x64.exe
  2. 一路下一步即可，默认装到你自己的用户目录：
        C:\\Users\\<你的用户名>\\AppData\\Local\\Programs\\掌中界
     不会弹 UAC、不会动系统目录。
  3. 第一次装如果提示缺 Microsoft Edge WebView2 运行时，安装器会自动装（那一步要联网）。

打开之后
  · 全新安装会直接进一张空画布（叫「项目一」），不会问你什么。
    （如果哪天它问「继续上次的掌中界？」，选最右边的「打开默认桌布」就行。）
  · 左边一条竖栏是工具栏：新建 / 网页 / 文件夹 / 便签 / 模板 / 设置 等。
  · 画布上：拖窗口上方的标题栏（鼠标移上去才出现）就能移动卡片。
  · 桌面会生成「掌中界」快捷方式（默认勾好的），开始菜单里还有「使用手册」。
  · 觉得字小/看不清：设置 →「界面字号」有小/标准/大/特大四档，整站一起放大。
  · 完全没头绪就先看手册：设置 →「使用手册 → 打开使用手册…」，
    或者直接双击安装目录（1-安装包\使用手册.html）里那份电子版。

=================================
重点想请你试的四件事
=================================

先做一步：设置（左栏齿轮，或 Ctrl+,）→「画布风格」→ 选【白板风（浅色纸感）】。
下面 1~3 的效果只有白板风才有（默认的「深色玻璃」故意不推开挡路的卡）。

1) 推开草纸 —— 左右
   画布空白处右键 → 新建便签，放三张，摆成一排。
   拖【中间那张】的标题栏往左推：左边那张应该被推开（多留一条缝）。
   手别松开，继续往右推：右边的卡应该被【往右】推开，不能被你盖上去。

2) 推开草纸 —— 上下 + 松手不回弹
   两张卡上下摆。拖下面那张往上推：上面那张应该往上让开（不是往左跑）。
   推过去再往回拖：被推开的卡不许自己弹回原位；手停住时它也不许自己动。

3) Ctrl + 拖标题栏 = 拖出一份副本
   按住 Ctrl 再拖标题栏：原件和旁边的卡都不许动，只有副本跟着鼠标走。

4) 新装上手
   空画布正中间会有一张新手引导卡（三条 + 「打开使用手册」）。点「知道了」它就不再出现。
   设置 →「界面字号」四档各试一下，看是不是整站一起放大（卡片、菜单、面板都跟着变）。

5) 模板库
   点左栏「模板」：浮层应该在窗口正中，标题行中间有胶囊搜索框，
   一排三张卡（当前画布 / 你的模板 / 保存为模板），三张应该一样高、边框一样。

=================================
不是 bug 的几点（省得你白报）
=================================
· 默认「深色玻璃」皮肤下，拖卡片【不会】推开挡路的卡 —— 白板风才有。
· 网页卡 / 文件夹卡是嵌进画布的真实窗口，第一次打开会慢几秒。

=================================
怎么反馈（这个最重要）
=================================
· 用截图或录屏（Bandicam、Win+G 都行）+ 一句话说清：
     "我往【右】推中间那张，结果右边那张【往左】跑了"
  —— 写出【我做了什么 → 我以为会怎样 → 实际怎样】，我就能直接定位。
· 反馈模板见同目录「测试反馈-照着填.txt」。

出厂状态说明
  · 这个安装包是"干净出厂"的：装完只有程序本身，画布是空的、模板库是空的，
    里面不含任何别人用过的画布 / 模板 / 设置。

卸载 / 数据在哪
  · 卸载：设置 → 应用 → 已安装的应用 → 掌中界。
  · 你的数据都在  C:\\Users\\<你的用户名>\\AppData\\Local\\掌中界 ；卸载不会删它。
EOF

cat > "$STAGE/测试反馈-照着填.txt" <<'EOF'
掌中界 · 测试反馈
========================================

1) 你的系统
   Windows 版本（设置 → 系统 → 关于，复制那一行就行）：
   屏幕分辨率 + 缩放（比如 2560x1440 / 150%）：

2) 出问题时的画布风格（选一个）
   [ ] 默认（深色玻璃）   [ ] 白板风（浅色纸感）   [ ] 白板风（深色）

3) 我做了什么（越具体越好）
   我按住的卡片：
   我往哪个方向拖的（左 / 右 / 上 / 下，或者先左后上）：
   鼠标大概移了多远 / 推了多久：

4) 我以为会发生
5) 实际发生的是（哪张卡、往哪跑了、有没有弹回来、有没有一跳一跳）：
6) 能重现吗
   [ ] 每次都出现   [ ] 偶尔     [ ] 只出现过一次
7) 附件（截图 / 录屏，文件名比如 推卡片1.mp4）：

========================================
把这份 + 截图/录屏一起发回来就行。谢谢！
EOF

ZIP="$DEST/掌中界-测试包-$VER.zip"
rm -f "$ZIP"
powershell -NoProfile -Command "Compress-Archive -Path '$(printf '%s' "$STAGE" | sed -E 's|^/([a-zA-Z])/|\1:/|')\\*' -DestinationPath '$(printf '%s' "$ZIP" | sed -E 's|^/([a-zA-Z])/|\1:/|')' -CompressionLevel Optimal -Force" >/dev/null
rm -rf "$STAGE"
python - "$(printf '%s' "$ZIP" | sed -E 's|^/([a-zA-Z])/|\1:/|')" <<'PY'
import sys, zipfile, os, hashlib
p = sys.argv[1]
print('zip:', p, os.path.getsize(p), 'B')
with zipfile.ZipFile(p) as z:
    for i in z.infolist(): print('  内含:', i.filename, i.file_size, 'B')
    print('完整性:', '正常' if z.testzip() is None else '损坏')
PY
echo "TEST-PACKAGE-DONE $VER"
